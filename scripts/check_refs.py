#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Check that every grammar cross-reference points at a section that exists.

The textbook and the grammar refer to each other by section number -
[§4.2]{.gref} in a lesson, "(§13.7)" in the grammar - and those numbers are
generated by pandoc from the order of the files and of the headings inside
them. Nothing enforces that a reference names a real section, so a heading
inserted in the wrong place silently rots every later number.

Chapter numbers come from the order of grammar/*.md, skipping the unnumbered
introduction; subsection numbers from the order of H2 headings in each file.
References inside a citation of another grammar (Smyth, Kuehner-Gerth) are
not ours and are ignored.
"""
import io
import os
import re
import sys
from glob import glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = re.compile(r"§(\d+(?:\.\d+)?)")
FOREIGN = re.compile(r"(?:Smyth|Kühner|Kuehner|Goodwin)[^.]{0,40}$")


def sections():
    """Map every section number the grammar defines to its heading."""
    found, chapter = {}, 0
    for path in sorted(glob(os.path.join(ROOT, "grammar", "*.md"))):
        lines = io.open(path, encoding="utf-8").read().split("\n")
        h1 = next(l for l in lines if l.startswith("# "))
        if "{.unnumbered}" in h1:
            continue
        chapter += 1
        found[str(chapter)] = h1[2:].strip()
        n = 0
        for line in lines:
            if line.startswith("## ") and "{.unnumbered}" not in line:
                n += 1
                found["%d.%d" % (chapter, n)] = line[3:].strip()
    return found


def main():
    known = sections()
    bad = []
    files = (sorted(glob(os.path.join(ROOT, "book", "*", "*.md"))) +
             sorted(glob(os.path.join(ROOT, "grammar", "*.md"))))
    for path in files:
        rel = os.path.relpath(path, ROOT)
        for i, line in enumerate(io.open(path, encoding="utf-8"), 1):
            for m in REF.finditer(line):
                if m.group(1) in known:
                    continue
                if FOREIGN.search(line[:m.start()]):
                    continue        # Smyth's numbering, not ours
                bad.append("%s:%d: no such section: %s" % (rel, i, m.group(0)))

    for b in bad:
        print("ERROR:   " + b)
    print("\nchecked %d files against %d grammar sections - %d dangling"
          % (len(files), len(known), len(bad)))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
